// MARK: - Timeline

enum PlataTimeline {
    /// El cuerpo sigue a la punta con este retraso (en unidades de arco): el borde redondo del trazo queda siempre tapado por la punta.
    static let lag = 40.0
    static let start = 0.36                                   // cuándo arranca el trazo
    static let total = start + PlataPath.duration + 0.22      // luego se cambia al logo estático

    static func clamp(_ v: Double, _ lo: Double = 0, _ hi: Double = 1) -> Double { min(hi, max(lo, v)) }
    static func smooth(_ t: Double) -> Double { t * t * (3 - 2 * t) }
    /// Progreso 0...1 de t entre a y b.
    static func seg(_ t: Double, _ a: Double, _ b: Double) -> Double { clamp((t - a) / (b - a)) }

    /// Resorte amortiguado 0 -> 1 con ~8 % de overshoot (sin curvas cúbicas "de manual").
    static func spring(_ tau: Double) -> Double {
        if tau <= 0 { return 0 }
        let z = 0.63, w = 26.0
        let wd = w * (1 - z * z).squareRoot()
        return 1 - exp(-z * w * tau) * (cos(wd * tau) + z / (1 - z * z).squareRoot() * sin(wd * tau))
    }

    /// Arco recorrido en el instante t (las tablas son monótonas).
    static func arc(_ t: Double) -> Double {
        let u = t - start
        if u <= 0 { return 0 }
        if u >= PlataPath.duration { return Double(PlataPath.count) }
        var lo = 0, hi = PlataPath.count
        while hi - lo > 1 {
            let m = (lo + hi) / 2
            if PlataPath.t[m] <= u { lo = m } else { hi = m }
        }
        let f = (u - PlataPath.t[lo]) / (PlataPath.t[hi] - PlataPath.t[lo])
        return Double(lo) + f
    }

    static func sample(_ table: [Double], _ s: Double) -> Double {
        let i = min(PlataPath.count - 1, Int(s))
        return table[i] + (table[i + 1] - table[i]) * (s - Double(i))
    }
}


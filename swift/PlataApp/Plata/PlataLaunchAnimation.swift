        let py = T.sample(PlataPath.y, s)
                let grow = 0.3 + 0.7 * T.smooth(T.clamp(s / (Double(PlataPath.count) * 0.62)))
        let intro = t < T.start + 0.1 ? T.clamp(T.spring((t - (T.start - 0.03)) * 1.1), 0, 1.12) : 1
        let headScale = max(0.0001, grow * intro)

        ZStack {
            // Cuerpo de la flecha: el logo, revelado por el trazo
            PlataGeometry.arrow
                .fill(ink)
                .mask(TraceMask(s: max(0, s - T.lag)))
                .mask(BodyCutMask())
                .mask(LogoMask())

            // Letras: pop con resorte cuando la piedra las alcanza (siempre recortadas del logo final)
            ForEach(0..<PlataGeometry.letterPaths.count, id: \.self) { i in
                let l = PlataGeometry.letterPaths[i]
                let tau = t - l.t0
                if tau > 0 {
                    let p = T.spring(tau)
                    l.path
                        .fill(ink)
                        .mask(LogoMask())
                        .scaleEffect(0.35 + 0.65 * p,
                                     anchor: UnitPoint(x: l.pivot.x / size.width, y: l.pivot.y / size.height))
                        .offset(y: CGFloat((1 - p) * 14))
                        .opacity(T.clamp(tau / 0.09))
                }
            }

            // Punta: viaja al frente del trazo; al final queda en su sitio exacto
            if t >= T.start - 0.03 {
                PlataGeometry.logo
                    .fill(ink)
                    .mask(HeadShapeMask())
                    .scaleEffect(headScale, anchor: unit)
                    .offset(x: CGFloat(px) - pivot.x, y: CGFloat(py) - pivot.y)
            }

            // El logo final entra con un fundido corto por encima (solo aporta bordes de menos de 1 px)
            PlataGeometry.logo
                .fill(ink)
                .opacity(T.smooth(T.seg(t, T.total - 0.20, T.total - 0.08)))
        }
    }
}

// MARK: - Vista pública

struct PlataLaunchAnimation: View {
    var onFinished: () -> Void = {}

    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    @State private var startDate: Date?
    @State private var done = false

    var body: some View {
        LogoCanvas {
            if done || reduceMotion {
                PlataGeometry.logo.fill(PlataGeometry.green)
            } else {
                TimelineView(.animation) { ctx in
                    PlataFrame(t: startDate.map { ctx.date.timeIntervalSince($0) } ?? 0)
                }
            }
        }
        .onAppear {
            startDate = Date()
            let delay = reduceMotion ? 0.4 : PlataTimeline.total
            DispatchQueue.main.asyncAfter(deadline: .now() + delay) {
                done = true
                onFinished()
            }
        }
    }
}

